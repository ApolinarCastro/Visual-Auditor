"""Extract category membership from a Ripley product/listing URL.

The PDP breadcrumb can be brand-only ("Moda Mujer > Marcas Casuales > Nicopoly")
even when the product is correctly listed in a commercial leaf. The listing
URL carries the real membership in `prodNavFullCategory` and `cat`.
"""
from __future__ import annotations

from urllib.parse import parse_qs, unquote_plus, urlparse


def _clean_path(text: str) -> str:
    return " → ".join(p.strip() for p in text.replace(">", "→").split("→") if p.strip())


def category_from_product_url(url: str | None) -> dict | None:
    if not url:
        return None
    try:
        qs = parse_qs(urlparse(str(url)).query)
    except Exception:
        return None
    full = (qs.get("prodNavFullCategory") or qs.get("prodNavFullCategory[]") or [None])[0]
    if full:
        category = _clean_path(unquote_plus(str(full)))
        if category:
            parts = [p.strip() for p in category.split("→") if p.strip()]
            return {
                "category": category,
                "subcategory": parts[-1] if parts else category,
                "cat": (qs.get("cat") or [None])[0],
                "source": "LISTING_MEMBERSHIP_URL",
                "evidence": "prodNavFullCategory",
            }
    cat = (qs.get("cat") or [None])[0]
    if cat:
        # `cat` is a stable listing identifier (e.g. blusas_y_poleras).
        label = str(cat).replace("_", " ").strip().title()
        return {
            "category": label,
            "subcategory": label,
            "cat": cat,
            "source": "LISTING_CAT_PARAM",
            "evidence": "cat",
        }
    return None


def category_from_listing_url(url: str | None) -> dict | None:
    """Derive the commercial category path from the acquisition surface URL."""
    if not url:
        return None
    try:
        path = urlparse(str(url)).path.strip("/")
    except Exception:
        return None
    parts = [p.replace("-", " ").strip().title() for p in path.split("/") if p]
    if not parts:
        return None
    # Prefer the fashion hierarchy, but keep any real 2+ level category.
    category = " → ".join(parts[:4])
    return {"category": category, "subcategory": parts[-1],
            "source": "ACQUISITION_SURFACE", "evidence": "category_url"}


def acquisition_url(url: str | None) -> str:
    """Normalize a category template before handing it to a frozen scraper.

    Templates generated by live discovery carry the literal `{page}`; the
    scraper builds its own pagination. Passing `page={page}` returned 0
    products for every category not discovered by the legacy anchor parser.
    """
    text = str(url or "")
    text = text.replace("&page={page}", "").replace("?page={page}", "")
    text = text.replace("page={page}", "page=1").replace("{page}", "1")
    return text
